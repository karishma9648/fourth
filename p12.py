#function calling with returning type
def add(a,b):#formal argument
    c=a+b
    return c
def sub(a,b):
    c=a-b
    return c
def mul(a,b):
    c=a*b
    return c
def div(a,b):
    c=a//b
    return c
res=add(2,6)#actual parameter
print(res)
res=sub(2,6)
print(res)
res=mul(2,6)
print(res)
res=div(2,6)
